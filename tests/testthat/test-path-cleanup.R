test_that("literal cleanup preserves wildcard matches and adjacent paths", {
  root <- tempfile("literal-cleanup-")
  dir.create(root)
  on.exit(unlink(root, recursive = TRUE), add = TRUE)
  pairs <- list(c("entry[1]", "entry1"))
  if (.Platform$OS.type != "windows") {
    pairs <- c(pairs, list(c("entry*", "entry-neighbor"),
                          c("entry\\name", "entryname")))
  }
  for (pair in pairs) {
    target <- file.path(root, pair[[1L]])
    neighbor <- file.path(root, pair[[2L]])
    dir.create(target)
    dir.create(neighbor)
    writeLines("owned", file.path(target, "child[1]"))
    writeLines("keep", file.path(neighbor, "keep"))
    expect_identical(SplitAlignerR:::.unlink_literal(target, recursive = TRUE), 0L)
    expect_false(dir.exists(target))
    expect_identical(readLines(file.path(neighbor, "keep")), "keep")
  }
  literal <- file.path(root, "file[1]")
  neighbor <- file.path(root, "file1")
  writeLines("owned", literal)
  writeLines("keep", neighbor)
  expect_identical(SplitAlignerR:::.unlink_literal(literal), 0L)
  expect_false(file.exists(literal))
  expect_identical(readLines(neighbor), "keep")
  expect_identical(SplitAlignerR:::.unlink_literal(literal), 0L)
})

test_that("forced cleanup removes owned permissions and preserves symlink targets", {
  skip_on_os("windows")
  root <- tempfile("literal-symlink-")
  dir.create(root)
  on.exit(unlink(root, recursive = TRUE), add = TRUE)
  outside <- file.path(root, "outside")
  owned <- file.path(root, "owned[1]")
  dir.create(outside)
  dir.create(owned)
  keep <- file.path(outside, "keep")
  writeLines("keep", keep)
  expect_true(file.symlink(outside, file.path(owned, "link")))
  expect_true(file.symlink(file.path(root, "absent"), file.path(owned, "dangling")))
  writeLines("owned", file.path(owned, "readonly"))
  Sys.chmod(file.path(owned, "readonly"), mode = "0400")
  Sys.chmod(owned, mode = "0500")
  expect_identical(SplitAlignerR:::.unlink_literal(owned, recursive = TRUE, force = TRUE), 0L)
  expect_false(dir.exists(owned))
  expect_identical(readLines(keep), "keep")

  link <- file.path(root, "direct-link")
  expect_true(file.symlink(outside, link))
  expect_identical(SplitAlignerR:::.unlink_literal(paste0(link, "/"), recursive = TRUE), 0L)
  expect_false(file.exists(link))
  expect_identical(readLines(keep), "keep")
})

test_that("failed panel and support writes clean literal destination directories", {
  root <- tempfile("literal-write-")
  dir.create(root)
  on.exit(unlink(root, recursive = TRUE), add = TRUE)
  reference <- file.path(root, "reference.nwk")
  free <- file.path(root, "free.nwk")
  fixed <- file.path(root, "fixed.nwk")
  writeLines("((A,B),(C,D));", reference)
  writeLines("g1((A,B),(C,D));", free)
  writeLines("other((A,B),(C,D));", fixed)
  out <- file.path(root, "panel[1]")
  neighbor <- file.path(root, "panel1")
  dir.create(neighbor)
  writeLines("keep", file.path(neighbor, "keep"))
  expect_error(align_panel_to_disk(reference, free, out, mode = "paired",
                                  fixed_file = fixed), "same gene IDs")
  expect_false(dir.exists(out))
  expect_identical(readLines(file.path(neighbor, "keep")), "keep")

  result <- align_branches("((A,B),(C,D));", c(g1 = "((A,B),(C,D));"))
  out <- file.path(root, "support[1]")
  neighbor <- file.path(root, "support1")
  dir.create(neighbor)
  writeLines("keep", file.path(neighbor, "keep"))
  expect_error(SplitAlignerR:::.write_branch_support_files(
    result$support_table, 1, out))
  expect_false(dir.exists(out))
  expect_identical(readLines(file.path(neighbor, "keep")), "keep")
})

test_that("panel export removes its temporary file inside a literal directory", {
  root <- tempfile("literal-export-")
  dir.create(root)
  on.exit(unlink(root, recursive = TRUE), add = TRUE)
  reference <- file.path(root, "reference.nwk")
  genes <- file.path(root, "genes.nwk")
  writeLines("((A,B),(C,D));", reference)
  writeLines("g1((A:1,B:2):3,(C:4,D:5):6);", genes)
  panel <- file.path(root, "panel")
  align_panel_to_disk(reference, genes, panel)
  output <- file.path(root, "output[1]")
  neighbor <- file.path(root, "output1")
  dir.create(output)
  dir.create(neighbor)
  writeLines("keep", file.path(neighbor, "keep"))
  expect_silent(export_panel_matrix(panel, file.path(output, "success.tsv")))
  expect_identical(list.files(output), "success.tsv")
  testthat::local_mocked_bindings(
    panel_load_shard = function(...) stop("injected export read failure"),
    .package = "SplitAlignerR"
  )
  expect_error(export_panel_matrix(panel, file.path(output, "failed.tsv")),
               "injected export read failure")
  expect_identical(list.files(output), "success.tsv")
  expect_identical(readLines(file.path(neighbor, "keep")), "keep")
})
